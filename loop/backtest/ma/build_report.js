function table(headers, rows, widths, opts = {}) {
  const total = widths.reduce((a, b) => a + b, 0);
  const cell = (txt, w, o = {}) => new TableCell({
    width: { size: w, type: WidthType.DXA },
    shading: o.fill ? { type: ShadingType.CLEAR, fill: o.fill } : undefined,
    margins: { top: 50, bottom: 50, left: 70, right: 70 },
    children: [new Paragraph({
      alignment: o.align || AlignmentType.CENTER,
      children: [new TextRun({ text: String(txt), size: 16, font: F,
        bold: o.bold, color: o.color })] })],
  });
  return new Table({
    width: { size: total, type: WidthType.DXA },
    columnWidths: widths,
    rows: [
      new TableRow({ tableHeader: true, children: headers.map((h, i) =>
        cell(h, widths[i], { fill: NAVY, bold: true, color: 'FFFFFF' })) }),
      ...rows.map((r) => new TableRow({ children: r.map((c, i) => {
        let o = { align: i === 0 ? AlignmentType.LEFT : AlignmentType.CENTER };
        if (opts.rowColor) { const rc = opts.rowColor(r, i); if (rc) o = { ...o, ...rc }; }
        return cell(c, widths[i], o);
      }) })),
    ],
  });
}

