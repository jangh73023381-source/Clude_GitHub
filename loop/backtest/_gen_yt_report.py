from docx.shared import Pt, RGBColor, Cm
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.oxml.ns import qn
from docx.oxml import OxmlElement

NAVY = RGBColor(0x1F, 0x38, 0x64); GREEN = RGBColor(0x1E, 0x7B, 0x34); RED = RGBColor(0xC0, 0x00, 0x00)
FONT = "Malgun Gothic"
doc = Document()
st = doc.styles['Normal']; st.font.name = FONT; st.font.size = Pt(10)
st.element.rPr.rFonts.set(qn('w:eastAsia'), FONT)
for s in doc.sections:
    s.top_margin = Cm(1.8); s.bottom_margin = Cm(1.8); s.left_margin = Cm(2); s.right_margin = Cm(2)


def _f(run, sz, bold=False, color=None):
    run.font.name = FONT; run.font.size = Pt(sz); run.bold = bold
    run._element.rPr.rFonts.set(qn('w:eastAsia'), FONT)
    if color is not None:
        run.font.color.rgb = color


def title(t):
    p = doc.add_paragraph(); _f(p.add_run(t), 16, True, NAVY)


def h2(t):
    p = doc.add_paragraph(); p.paragraph_format.space_before = Pt(9); _f(p.add_run(t), 13, True, NAVY)


def h3(t):
    p = doc.add_paragraph(); p.paragraph_format.space_before = Pt(5); _f(p.add_run(t), 10.5, True, NAVY)


def para(t, sz=10, color=None):
    p = doc.add_paragraph(); _f(p.add_run(t), sz, False, color); return p


def bullet(t, sz=9.5, bold=False):
    p = doc.add_paragraph(style='List Bullet'); _f(p.add_run(t), sz, bold); return p


def callout(t, color=GREEN, fill='E2EFDA'):
    p = doc.add_paragraph(); _f(p.add_run(t), 10, True, color)
    pPr = p._p.get_or_add_pPr(); sh = OxmlElement('w:shd'); sh.set(qn('w:fill'), fill); pPr.append(sh)


def shade(cell, hexc):
    tcPr = cell._tc.get_or_add_tcPr(); sh = OxmlElement('w:shd'); sh.set(qn('w:fill'), hexc); tcPr.append(sh)


def make_table(headers, rows, widths, hl=None):
    t = doc.add_table(rows=1, cols=len(headers)); t.alignment = WD_TABLE_ALIGNMENT.LEFT
    t.style = 'Table Grid'; t.autofit = False; t.allow_autofit = False
    hc = t.rows[0].cells
    for i, h in enumerate(headers):
        hc[i].width = Cm(widths[i]); shade(hc[i], '1F3864')
        _f(hc[i].paragraphs[0].add_run(h), 8, True, RGBColor(0xFF, 0xFF, 0xFF))
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].width = Cm(widths[i])
            s = str(v)
            col = GREEN if ('✅' in s) else (RED if ('❌' in s) else None)
            if hl is not None and i in hl and col is None:
                try:
                    col = GREEN if float(s.replace('%p', '').replace('+', '')) > 0 else RED
                except ValueError:
                    pass
            _f(cells[i].paragraphs[0].add_run(s), 8, False, col)
    return t


