def setfont(run, size=10, bold=False, color=None):
    run.font.name = FONT
    run.font.size = Pt(size)
    run.bold = bold
    if color is not None:
        run.font.color.rgb = color
    run._element.rPr.rFonts.set(qn('w:eastAsia'), FONT)


def title(doc, text):
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    setfont(p.add_run(text), 16, True, NAVY)


def section(doc, text):
    p = doc.add_paragraph(); p.paragraph_format.space_before = Pt(12)
    setfont(p.add_run(text), 13, True, NAVY)


def sub(doc, text):
    p = doc.add_paragraph(); p.paragraph_format.space_before = Pt(6)
    setfont(p.add_run(text), 10.5, True)


def body(doc, text, size=9.5, color=None, bold=False):
    p = doc.add_paragraph(); p.paragraph_format.space_after = Pt(3)
    setfont(p.add_run(text), size, bold, color)
    return p


def bullet(doc, text, size=9.5):
    p = doc.add_paragraph(style='List Bullet')
    p.paragraph_format.space_after = Pt(2)
    setfont(p.add_run(text), size)


def note(doc, text):
    p = doc.add_paragraph(); p.paragraph_format.space_after = Pt(3)
    setfont(p.add_run(text), 8.5, False, RGBColor(0x55, 0x55, 0x55))


def shade(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr()
    el = OxmlElement('w:shd'); el.set(qn('w:val'), 'clear')
    el.set(qn('w:fill'), hexcolor); tcPr.append(el)


def table(doc, headers, rows, widths=None, hl=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Table Grid'; t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        c = t.rows[0].cells[i]; c.text = ''
        shade(c, '1F3864')
        r = c.paragraphs[0].add_run(h)
        c.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
        setfont(r, 8, True, RGBColor(0xFF, 0xFF, 0xFF))
    for ri, row in enumerate(rows):
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ''
            p = cells[i].paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER if i else WD_ALIGN_PARAGRAPH.LEFT
            setfont(p.add_run(str(v)), 8, bool(hl and ri in hl))
            if hl and ri in hl:
                shade(cells[i], 'FFF2CC')
    if widths:
        for r in t.rows:
            for i, w in enumerate(widths):
                r.cells[i].width = Cm(w)
    return t


