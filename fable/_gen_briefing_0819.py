def _cell(x):
    if not x:
        return "없음"
    return f"{x['price']:,.0f} ({x['pct']:+.1f}%, {x['atr']:+.2f}ATR) {x['label']}"


def _zone(r):
    p = r.get('p120')
    if p is None:
        return "—"
    s = f"{p:.2f}"
    if 0.80 <= p <= 0.95:
        s += " 저항선 직하(최강)"
    elif 0.40 <= p <= 0.60:
        s += " 중간(최약)"
    return s


