_add_run_orig = add_run


def add_run(para, text, size, bold=False, color=None):
    t = str(text)
    if '**' not in t:
        return _add_run_orig(para, t, size, bold, color)
    r = None
    for i, seg in enumerate(t.replace('\\*', '*').split('**')):
        if seg:
            r = _add_run_orig(para, seg, size, bold or (i % 2 == 1), color)
    return r


