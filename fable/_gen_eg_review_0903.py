_add_run_orig = add_run
def add_run(para, text, size, bold=False, color=None):
    parts = str(text).split('**')
    for i, seg in enumerate(parts):
        if seg == '':
            continue
        _add_run_orig(para, seg, size, bold or (i % 2 == 1), color)
def make_table(headers, rows, colwidths=None):
    t = doc.add_table(rows=1, cols=len(headers))
    set_table_borders(t)
    t.autofit = False
    hdr = t.rows[0]
    for i, htext in enumerate(headers):
        cell = hdr.cells[i]; cell.text = ""
        add_run(cell.paragraphs[0], htext, 8, True, RGBColor(0xFF, 0xFF, 0xFF))
        shade(cell._tc.get_or_add_tcPr(), "1F3864")
    for rdata in rows:
        cells = t.add_row().cells
        for i, val in enumerate(rdata):
            cells[i].text = ""
            add_run(cells[i].paragraphs[0], str(val), 8, False)
    if colwidths:
        tot = sum(colwidths); scale = min(1.0, 10400 / tot)
        tblPr = t._tbl.tblPr
        lay = OxmlElement('w:tblLayout'); lay.set(qn('w:type'), 'fixed'); tblPr.append(lay)
        grid = t._tbl.tblGrid
        for i, gc in enumerate(grid.findall(qn('w:gridCol'))):
            gc.set(qn('w:w'), str(int(colwidths[i] * scale)))
        for i, w in enumerate(colwidths):
            t.columns[i].width = _Tw(int(w * scale))
        for row in t.rows:
            for i, w in enumerate(colwidths):
                row.cells[i].width = _Tw(int(w * scale))
    return t

