from docx import Document
from docx.shared import Pt, RGBColor
from docx.oxml.ns import qn
from docx.oxml import OxmlElement
from docx.enum.text import WD_LINE_SPACING

# 렌더링 안정성 수정(2026-07-20 반영): 생성 환경(Linux/LibreOffice)에는 "맑은 고딕"이 설치돼
# 있지 않아 PDF 변환 시 폰트가 대체되고, 일부 PDF 미리보기 렌더러(특히 음영 박스 문단)에서
# 줄 간격이 무너져 텍스트가 겹치는 문제가 실제 발생했다(사용자 리포트). 실제 설치된 CJK 폰트
# (Noto Sans CJK KR)를 사용하고 모든 문단에 명시적 줄간격(1.15배)을 지정해 렌더러에 관계없이
# 안정적으로 표시되도록 한다. 매 데일리 브리핑 생성 스크립트는 이 헤더를 그대로 재사용한다.
# 참고: 이 환경에는 컬러 이모지 폰트도 설치돼 있지 않아 🔴🟡🟢 등 이모지는 빈 사각형(tofu)으로
# 표시된다. 강조 표시는 이모지 대신 "[위험]/[주의]/[호재]" 같은 대괄호 라벨 + 색상(RED_TXT/
# GREEN_TXT)으로 대체한다.
FONT = "Noto Sans CJK KR"
NAVY = RGBColor(0x1F, 0x38, 0x64)
GREEN_TXT = RGBColor(0x1E, 0x7B, 0x34)

doc = Document()
for s in doc.sections:
    s.left_margin = s.right_margin = s.top_margin = s.bottom_margin = 457200

def shade(elem, hexcolor):
    sh = OxmlElement('w:shd')
    sh.set(qn('w:val'), 'clear')
    sh.set(qn('w:fill'), hexcolor)
    elem.append(sh)

def _fix_line_spacing(p):
    pf = p.paragraph_format
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    pf.line_spacing = 1.15

def add_run(para, text, size, bold=False, color=None):
    r = para.add_run(text)
    r.font.name = FONT
    r.font.size = Pt(size)
    r.bold = bold
    if color:
        r.font.color.rgb = color
    r._element.rPr.rFonts.set(qn('w:eastAsia'), FONT)
    return r

def para(runs, space_before=0, space_after=60, shading=None):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.space_before = Pt(space_before)
    pf.space_after = Pt(space_after)
    _fix_line_spacing(p)
    for (text, size, bold, color) in runs:
        add_run(p, text, size, bold, color)
    if shading:
        shade(p._p.get_or_add_pPr(), shading)
    return p

def title(text):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(3)
    _fix_line_spacing(p)
    add_run(p, text, 16, True, NAVY)
    return p

def section(text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(10)
    p.paragraph_format.space_after = Pt(5)
    _fix_line_spacing(p)
    add_run(p, text, 13, True, NAVY)
    return p

def subsection(text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(4)
    p.paragraph_format.space_after = Pt(3)
    _fix_line_spacing(p)
    add_run(p, text, 10.5, True)
    return p

def note(text, size=8.5):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(4)
    _fix_line_spacing(p)
    add_run(p, text, size, False)
    return p

def labelpara(label, rest, size=10):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(4)
    _fix_line_spacing(p)
    add_run(p, label, size, True)
    add_run(p, rest, size, False)
    return p

def bullet(text, size=9.5):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(3)
    _fix_line_spacing(p)
    add_run(p, text, size, False)
    return p

def set_table_borders(t, color="BFBFBF", sz=2):
    tbl = t._tbl
    tblPr = tbl.tblPr
    borders = OxmlElement('w:tblBorders')
    for edge in ('top','left','bottom','right','insideH','insideV'):
        el = OxmlElement(f'w:{edge}')
        el.set(qn('w:val'), 'single')
        el.set(qn('w:sz'), str(sz))
        el.set(qn('w:color'), color)
        borders.append(el)
    tblPr.append(borders)

def make_table(headers, rows, colwidths=None):
    t = doc.add_table(rows=1, cols=len(headers))
    set_table_borders(t)
    t.autofit = True
    hdr = t.rows[0]
    for i, htext in enumerate(headers):
        cell = hdr.cells[i]
        cell.text = ""
        p = cell.paragraphs[0]
        add_run(p, htext, 8, True, RGBColor(0xFF,0xFF,0xFF))
        shade(cell._tc.get_or_add_tcPr(), "1F3864")
    for rdata in rows:
        cells = t.add_row().cells
        for i, val in enumerate(rdata):
            cell = cells[i]
            cell.text = ""
            p = cell.paragraphs[0]
            add_run(p, str(val), 8, False)
    return t

