_ATR_CACHE = {}


def _부록(key):
    """상설 부록(_각주_부록.py)의 일일 1줄 경고. 근거·한계 전문은 부록 문서에 있다."""
    import os, sys, importlib
    d = os.path.dirname(os.path.abspath(__file__))
    if d not in sys.path:
        sys.path.insert(0, d)
    try:
        return importlib.import_module('_각주_부록').short(key)
    except Exception:
        return ''


def _atr_won(code, close):
    """종목별 ATR14(원). etf_levels(키움 일봉, 조회 전용)에서 산출하고 실패하면 None."""
    if code in _ATR_CACHE:
        return _ATR_CACHE[code]
    a = None
    try:
        import importlib.util as _il
        import os as _os
        _p = _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), 'etf_levels.py')
        _s = _il.spec_from_file_location('_etflv', _p)
        _m = _il.module_from_spec(_s)
        _s.loader.exec_module(_m)
        b = _m.bars(code)
        if b:
            a = _m.atr(b)
    except Exception:
        a = None
    _ATR_CACHE[code] = a
    return a


